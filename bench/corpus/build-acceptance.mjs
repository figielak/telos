#!/usr/bin/env node
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { UsageError } from '../../lib/errors.mjs';

// Builds the self-contained hidden acceptance scripts (PROTOCOL §4.2, D-06) from their sources:
//   <repo>/acceptance/src/<task>/spec.json   { start, testPatterns[], regression, pre?, behavioural, env? }
//   <repo>/acceptance/src/<task>/hidden/**   behavioural test files, copied into the work tree at the same paths
// → <repo>/acceptance/<task>.mjs. The grader copies one script out of the corpus, so the script embeds everything.
// Exit codes of a built script: 0 accepted, 1 behavioural check fails, 2 regression check fails (bench/calibrate.mjs).

const walk = (dir, base = dir) => readdirSync(dir).flatMap((name) => {
  const full = join(dir, name);
  return statSync(full).isDirectory() ? walk(full, base) : [relative(base, full)];
});

const RUNTIME = String.raw`
import { spawnSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const tests = SPEC.testPatterns.map((p) => new RegExp(p));
const isTest = (path) => tests.some((re) => re.test(path));
const git = (args, input) => spawnSync('git', args, { encoding: 'utf8', input, maxBuffer: 256 << 20 });
const lines = (text) => text.split('\n').filter(Boolean);
const run = (cmd) => spawnSync('bash', ['-c', cmd], { stdio: 'inherit', env: { ...process.env, ...SPEC.env } }).status === 0;

// Original suite (§4.2): every test path that is not in the start commit is removed (added, renamed, copied or
// untracked, ignored files included), then every test file of the start commit is restored.
const original = lines(git(['ls-tree', '-r', '--name-only', SPEC.start]).stdout).filter(isTest);
const known = new Set(original);
const present = [...lines(git(['ls-files', '--cached']).stdout), ...lines(git(['ls-files', '-o']).stdout)];
for (const path of present.filter((p) => isTest(p) && !known.has(p) && !p.split('/').includes('node_modules'))) rmSync(path, { force: true });
const restored = git(['checkout', SPEC.start, '--pathspec-from-file=-', '--'], original.join('\n'));
if (restored.status !== 0) { console.error('cannot restore the original tests: ' + restored.stderr); process.exit(2); }

if (!run(SPEC.regression)) process.exit(2);

for (const [path, body] of Object.entries(SPEC.hidden)) {
  mkdirSync(dirname(join(process.cwd(), path)), { recursive: true });
  writeFileSync(path, body);
}
if (SPEC.pre && !run(SPEC.pre)) process.exit(1);
process.exit(run(SPEC.behavioural) ? 0 : 1);
`;

/** Script text for one task source directory. */
export function buildScript(srcDir) {
  const spec = JSON.parse(readFileSync(join(srcDir, 'spec.json'), 'utf8'));
  for (const field of ['start', 'testPatterns', 'regression', 'behavioural']) if (!spec[field]) throw new UsageError(`${srcDir}/spec.json: ${field} is required`);
  const hiddenDir = join(srcDir, 'hidden');
  const hidden = {};
  try { for (const rel of walk(hiddenDir).sort()) hidden[rel] = readFileSync(join(hiddenDir, rel), 'utf8'); } catch { /* no hidden files */ }
  if (!Object.keys(hidden).length) throw new UsageError(`${srcDir}/hidden: no behavioural test files`);
  const full = { start: spec.start, testPatterns: spec.testPatterns, regression: spec.regression, pre: spec.pre ?? null,
    behavioural: spec.behavioural, env: spec.env ?? {}, hidden };
  return `// Generated by bench/corpus/build-acceptance.mjs from ${srcDir.split('/').slice(-4).join('/')} - do not edit.\n`
    + `// Hidden acceptance (PROTOCOL §4.2): exit 0 accepted, 1 behavioural fails, 2 regression fails.\n`
    + `const SPEC = ${JSON.stringify(full, null, 1)};\n${RUNTIME}`;
}

/** Build every `<repo>/acceptance/src/<task>/` under `dir` → paths written. */
export function buildAll(dir) {
  const written = [];
  for (const repo of readdirSync(dir)) {
    const src = join(dir, repo, 'acceptance', 'src');
    let tasks;
    try { tasks = readdirSync(src); } catch { continue; }
    for (const task of tasks.sort()) {
      const out = join(dir, repo, 'acceptance', `${task}.mjs`);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, buildScript(join(src, task)));
      written.push(out);
    }
  }
  return written;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const i = process.argv.indexOf('--dir');
    const dir = resolve(i > 0 ? process.argv[i + 1] : dirname(process.argv[1]));
    for (const path of buildAll(dir)) process.stdout.write(`${path}\n`);
  } catch (e) {
    process.stderr.write(`${e.message}\n`);
    process.exitCode = e instanceof UsageError ? 2 : 1;
  }
}
